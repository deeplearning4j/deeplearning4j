namespace mlir {
namespace sd {

/// SD Dialect namespace
constexpr llvm::StringLiteral kSDDialectNamespace = "sd";

/// SD Data Types matching libnd4j DataType enum
enum class SDDataType : int32_t {
    INHERIT = 0,
    BOOL = 1,
    FLOAT8 = 2,
    HALF = 3,
    FLOAT16 = 3,  // Alias
    BHALF = 4,
    BFLOAT16 = 4,  // Alias
    FLOAT32 = 5,
    DOUBLE = 6,
    INT8 = 7,
    INT16 = 8,
    INT32 = 9,
    INT64 = 10,
    UINT8 = 11,
    UINT16 = 12,
    UINT32 = 13,
    UINT64 = 14,
    QINT8 = 15,
    QINT16 = 16,
    UTF8 = 50,
    UTF16 = 51,
    UTF32 = 52,
    ANY = 100
};

/// Convert MLIR element type to SD data type
SDDataType mlirTypeToSDDataType(Type type);

/// Convert SD data type to MLIR element type
Type sdDataTypeToMLIRType(MLIRContext *ctx, SDDataType dtype);

} // namespace sd
} // namespace mlir

