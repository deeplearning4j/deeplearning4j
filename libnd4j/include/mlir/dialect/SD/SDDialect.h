namespace mlir {
namespace sd {

/// SD Dialect - Operations for SameDiff/ND4J computations
class SDDialect : public Dialect {
public:
    explicit SDDialect(MLIRContext *context);

    /// Returns the namespace of the SD dialect
    static llvm::StringRef getDialectNamespace() { return kSDDialectNamespace; }

    /// Hook for materializing constants
    Operation *materializeConstant(OpBuilder &builder, Attribute value,
                                   Type type, Location loc) override;

    /// Parse a type registered to this dialect
    Type parseType(DialectAsmParser &parser) const override;

    /// Print a type registered to this dialect
    void printType(Type type, DialectAsmPrinter &os) const override;
};

} // namespace sd
} // namespace mlir

